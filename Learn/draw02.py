import turtle                   #导入模块
turtle.showturtle()             #显示箭头
turtle.write("写轮眼")          #写字符串
turtle.forward(300)             #前进300像素
turtle.color("blue")            #画笔颜色改为blue
turtle.left(90)                 #箭头左转90度
turtle.forward(300)             #向前300像素
turtle.goto(0,50)               #移动到（0，50）
turtle.goto(0,0)                #移动到（0，0）
turtle.penup()                  #抬起，移动不划线
turtle.goto(100,100)            #移动到（100，100）
turtle.pendown()                #放下笔开始划线
turtle.goto(0,0)                #移动到（0，0）
turtle.circle(50)               #画一个半径50的圆
